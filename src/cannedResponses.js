import fs from "node:fs";
import path from "node:path";
import { readConfig, checkPersonalityChanged } from "./config.js";

const ROOT = process.cwd();
const PHRASE_MANIFEST_PATH = path.join(ROOT, "data", "phrase-manifest.json");

// "filler" is the only stall-type category — a placeholder meant to be
// forgettable while the real reply is still cooking, never a line worth
// putting in a transcript. Every other category (greeting, custom acks,
// firmware/status announcements, ...) is a full line said *to* the person,
// so a text lookup is always attempted for it.
const STALL_CATEGORIES = new Set(["filler"]);

let cachedManifest = null;
function loadPhraseManifest() {
  if (cachedManifest) return cachedManifest;
  try {
    cachedManifest = JSON.parse(fs.readFileSync(PHRASE_MANIFEST_PATH, "utf8"));
  } catch {
    cachedManifest = {};
  }
  return cachedManifest;
}

// Looks up the spoken text for a canned line already chosen elsewhere
// (lineId, category) against data/phrase-manifest.json — the only place
// canned-response text is persisted (scripts/generate-stock-phrases.js
// writes `${category}_${index}.pcm` in the same order as
// manifest[category], so the numeric suffix is a direct array index back
// into it). Categories generated by the separate, manifest-free
// scripts/generate-canned-lines.js (e.g. "greeting") have no persisted text
// anywhere and correctly resolve to undefined here — callers omit the
// `text` field in that case rather than fabricate a line.
export function lookupCannedText(category, lineId) {
  if (!category || !lineId || STALL_CATEGORIES.has(category)) return undefined;
  const manifest = loadPhraseManifest();
  const entries = manifest[category];
  if (!Array.isArray(entries)) return undefined;

  const prefix = `${category}_`;
  if (!lineId.startsWith(prefix)) return undefined;
  const suffix = lineId.slice(prefix.length);
  // Digits only: Number() would also accept "", " 1", "0x1" and "1e0".
  if (!/^\d+$/.test(suffix)) return undefined;
  const index = Number(suffix);
  if (!Number.isInteger(index) || index < 0 || index >= entries.length) return undefined;
  return entries[index]?.text;
}

// Flat, not nested by personality — wiped wholesale on a personality switch
// (see checkPersonalityChanged), so it only ever holds one personality's
// history at a time.
let playedIds = { friendly: {}, sentry_intruder: {}, shared: {} };

function listResponseFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => {
      // Ignore dotfiles (.gitkeep, .DS_Store, etc.) — an empty folder must
      // resolve as empty, not as "one file called .gitkeep".
      if (name.startsWith(".")) return false;
      try {
        return fs.statSync(path.join(dir, name)).isFile();
      } catch {
        return false;
      }
    });
}

function resolveBucket(activePersonality, mode, category) {
  const modeDir = path.join(
    ROOT,
    "personalities",
    activePersonality,
    "canned-responses",
    mode,
    category,
  );
  const modeFiles = listResponseFiles(modeDir);
  if (modeFiles.length > 0) {
    return { bucket: mode, dir: modeDir, files: modeFiles };
  }

  const sharedDir = path.join(
    ROOT,
    "personalities",
    activePersonality,
    "canned-responses",
    "shared",
    category,
  );
  const sharedFiles = listResponseFiles(sharedDir);
  if (sharedFiles.length > 0) {
    return { bucket: "shared", dir: sharedDir, files: sharedFiles };
  }

  return null;
}

// Returns either { ok: true, lineId, bytes } or { ok: false, reason }.
export function getCannedResponse(mode, category) {
  const config = readConfig();
  const activePersonality = config.active_personality;
  const historyWindow = config.canned_response_history_window ?? 3;

  if (checkPersonalityChanged(activePersonality)) {
    playedIds = { friendly: {}, sentry_intruder: {}, shared: {} };
  }

  const resolved = resolveBucket(activePersonality, mode, category);
  if (!resolved) {
    return {
      ok: false,
      reason: `no canned responses available for category "${category}" (mode "${mode}", personality "${activePersonality}")`,
    };
  }

  const { bucket, dir, files } = resolved;
  playedIds[bucket] ??= {};
  const excluded = new Set(playedIds[bucket][category] ?? []);

  // If every file is excluded, ignore the exclusion rather than block.
  let candidates = files.filter((f) => !excluded.has(path.parse(f).name));
  if (candidates.length === 0) candidates = files;

  const chosenFile = candidates[Math.floor(Math.random() * candidates.length)];
  const lineId = path.parse(chosenFile).name;
  const bytes = fs.readFileSync(path.join(dir, chosenFile));

  const history = (playedIds[bucket][category] ??= []);
  history.push(lineId);
  if (history.length > historyWindow) {
    history.splice(0, history.length - historyWindow);
  }

  return { ok: true, lineId, bytes };
}
